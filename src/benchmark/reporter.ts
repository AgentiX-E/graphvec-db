/**
 * reporter.ts — Markdown report formatting for benchmark results
 */

import { BenchmarkBaseline, ComparisonRow, hasCriticalRegression, hasAnyRegression } from './baseline-store'

export function formatMarkdownReport(baseline: BenchmarkBaseline): string {
  const lines: string[] = []
  const date = new Date(baseline.createdAt).toISOString().slice(0, 19).replace('T', ' ')

  lines.push(`# Benchmark Report (${baseline.mode})`)
  lines.push(``)
  lines.push(`| | |`)
  lines.push(`|---|---|`)
  lines.push(`| **Date** | ${date} |`)
  lines.push(`| **Git hash** | \`${baseline.gitHash}\` |`)
  lines.push(`| **Mode** | ${baseline.mode} |`)
  lines.push(`| **Tests** | ${baseline.results.length} |`)
  lines.push(``)
  lines.push(`## Results`)
  lines.push(``)
  lines.push(`| Benchmark | ops/s | Duration (ms) | Samples |`)
  lines.push(`|---|---|---|---|`)

  for (const r of baseline.results) {
    const ops = r.opsPerSecond.toLocaleString()
    lines.push(`| ${r.name} | ${ops} | ${r.durationMs.toFixed(1)} | ${r.samples} |`)
  }

  lines.push(``)
  lines.push(`---`)
  lines.push(`*Report generated by benchmark runner*`)

  return lines.join('\n')
}

export function formatComparisonReport(current: BenchmarkBaseline, previous: BenchmarkBaseline): string {
  const { compareResults } = require('./baseline-store')
  const rows: ComparisonRow[] = compareResults(current, previous)

  const lines: string[] = []
  lines.push(`# Benchmark Comparison Report`)
  lines.push(``)
  lines.push(`| | Current | Previous |`)
  lines.push(`|---|---|---|`)
  lines.push(`| **Date** | ${new Date(current.createdAt).toISOString().slice(0, 10)} | ${new Date(previous.createdAt).toISOString().slice(0, 10)} |`)
  lines.push(`| **Git hash** | \`${current.gitHash}\` | \`${previous.gitHash}\` |`)
  lines.push(`| **Mode** | ${current.mode} | ${previous.mode} |`)
  lines.push(``)
  lines.push(`## Regression Summary`)
  lines.push(``)
  const critical = rows.filter(r => r.regression === 'critical').length
  const warning = rows.filter(r => r.regression === 'warning').length
  const passed = rows.filter(r => r.regression === 'none').length
  lines.push(`- ✅ Pass: ${passed}`)
  if (warning > 0) lines.push(`- ⚠️ Warning (5-10%): ${warning}`)
  if (critical > 0) lines.push(`- 🔴 Critical (>10%): ${critical}`)
  lines.push(``)
  lines.push(`## Detailed Comparison`)
  lines.push(``)
  lines.push(`| Benchmark | Current (ops/s) | Previous (ops/s) | Change % | Status |`)
  lines.push(`|---|---|---|---|---|`)

  for (const r of rows) {
    const status = r.regression === 'critical' ? '🔴' : r.regression === 'warning' ? '⚠️' : '✅'
    const change = r.changePercent > 0 ? `+${r.changePercent}` : `${r.changePercent}`
    lines.push(`| ${r.name} | ${r.currentOps.toLocaleString()} | ${r.previousOps.toLocaleString()} | ${change}% | ${status} |`)
  }

  lines.push(``)
  lines.push(`---`)
  if (hasCriticalRegression(rows)) {
    lines.push(`**Status: FAILED** — Critical regressions detected.`)
  } else if (hasAnyRegression(rows)) {
    lines.push(`**Status: WARNING** — Minor regressions detected.`)
  } else {
    lines.push(`**Status: PASSED** — No regression detected.`)
  }

  return lines.join('\n')
}
